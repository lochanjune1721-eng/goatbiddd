// scripts/build-battles-seed.mjs — turn the curated CSV into a seed file.
//
// The CSV is editorial: 100 boards, 20 contenders each, already in the order
// they should start in. Two things it cannot express on its own:
//
//   1. people.slug is globally unique, and 172 contenders appear on more than
//      one board (Messi is on Greatest Footballer AND Greatest Athlete). The
//      highest-ranked board keeps the clean slug; later ones get the board
//      appended, so /person?slug=lionel-messi is still the football Messi.
//   2. Every contender starts on $0, so total_cents cannot order the board and
//      first_backed_at is null. seed_rank carries the editorial order until
//      money starts moving it.
import fs from 'node:fs';

const src = process.argv[2];
const out = process.argv[3] || 'data/top-100-battles.sql';
if (!src) { console.error('usage: node scripts/build-battles-seed.mjs <csv> [out.sql]'); process.exit(1); }

// Small hand-rolled parser: the file has no quoted fields or embedded commas.
const lines = fs.readFileSync(src, 'utf8').replace(/^﻿/, '').trim().split(/\r?\n/);
const head = lines[0].split(',');
const rows = lines.slice(1).map(l => {
  const parts = l.split(',');
  return Object.fromEntries(head.map((h, i) => [h.trim(), (parts[i] ?? '').trim()]));
});

const slugify = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '')
  .toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const q = s => `'${String(s).replace(/'/g, "''")}'`;

const boards = new Map();
for (const r of rows) {
  if (!boards.has(r.category)) boards.set(r.category, { rank: Number(r.category_rank), people: [] });
  boards.get(r.category).people.push({ name: r.contender, rank: Number(r.contender_rank) });
}

// Best board for each name wins the clean slug.
const best = new Map();
for (const [cat, b] of boards)
  for (const p of b.people) {
    const s = slugify(p.name);
    const prev = best.get(s);
    if (!prev || b.rank < prev.rank || (b.rank === prev.rank && p.rank < prev.prank))
      best.set(s, { cat, rank: b.rank, prank: p.rank });
  }

const sql = [];
sql.push(`-- data/top-100-battles.sql — GENERATED by scripts/build-battles-seed.mjs`);
sql.push(`-- Source: ${src.split('/').pop()}`);
sql.push(`-- ${boards.size} boards, ${rows.length} contenders. Re-runnable: every write is`);
sql.push(`-- guarded, so an existing board keeps whatever money is already on it.`);
sql.push(`--`);
sql.push(`-- Needs people.seed_rank — run supabase-seed-rank.sql (or supabase.sql) first.`);
sql.push('');
sql.push('begin;');
sql.push('');

for (const [cat, b] of [...boards].sort((a, c) => a[1].rank - c[1].rank)) {
  const cslug = slugify(cat);
  const group = cat.replace(/^Greatest\s+/i, '').trim();
  sql.push(`-- ── #${b.rank} ${cat} ${'─'.repeat(Math.max(0, 54 - cat.length))}`);
  sql.push(`insert into categories (slug,name,group_name,sort_order) values (${q(cslug)},${q(cat)},${q(group)},${b.rank})`);
  sql.push(`  on conflict (slug) do update set name=excluded.name, sort_order=excluded.sort_order;`);
  const vals = b.people.map(p => {
    const base = slugify(p.name);
    const owner = best.get(base);
    const pslug = (owner && owner.cat === cat) ? base : `${base}-${cslug.replace(/^greatest-/, '')}`;
    return `  (${q(pslug)},(select id from categories where slug=${q(cslug)}),${q(p.name)},${p.rank},` +
           `${q('https://en.wikipedia.org/wiki/' + p.name.replace(/ /g, '_'))})`;
  });
  sql.push(`insert into people (slug,category_id,name,seed_rank,wikipedia_url) values`);
  sql.push(vals.join(',\n'));
  // A board already carrying money keeps it; only the editorial order is refreshed.
  sql.push(`  on conflict (slug) do update set seed_rank=excluded.seed_rank, category_id=excluded.category_id;`);
  sql.push('');
}
// Everything else is pushed below the hundred. Without this the boards seeded
// by supabase.sql sit at sort_order 1..83 and interleave with these, so the
// "top 100 battles" would be whichever board happened to claim a number.
sql.push(`-- ── Keep the hundred on top ─────────────────────────────────────────`);
sql.push(`update categories set sort_order = sort_order + 1000`);
sql.push(` where sort_order < 1000 and slug not in (`);
sql.push('   ' + [...boards.keys()].map(c => q(slugify(c))).join(',\n   '));
sql.push(` );`);
sql.push('');
sql.push('commit;');
fs.writeFileSync(out, sql.join('\n') + '\n');

const reused = [...best.values()].length;
console.log(`${out}: ${boards.size} boards, ${rows.length} contenders, ${sql.length} lines`);
console.log(`unique names: ${reused} — the rest carry a board-suffixed slug`);
